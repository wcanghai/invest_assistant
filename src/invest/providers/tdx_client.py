class TdxClient:
    """通达信客户端接口代理。方法名与官方 tq 接口保持一致。"""

    def __init__(self, script_file: Optional[str] = None, api: Any = None) -> None:
        # 初始化客户端并保存策略文件路径和可选的底层 API 对象。
        self.script_file = script_file
        self.tq = api

    @property
    def api(self) -> Any:
        # 延迟加载并返回通达信 tq API 对象。
        if self.tq is None:
            try:
                from tqcenter import tq
            except ImportError as exc:
                raise RuntimeError(
                    "未找到 tqcenter，请在通达信 PYPlugins 环境中运行，或注入 api"
                ) from exc
            self.tq = tq
        return self.tq

    def _call(self, name: str, *args: Any, **kwargs: Any) -> Any:
        # 根据接口名称调用底层通达信 API。
        return getattr(self.api, name)(*args, **kwargs)

    def initialize(self, script_file: Optional[str] = None) -> Any:
        # 初始化当前策略与通达信客户端的连接。
        return self._call("initialize", script_file or self.script_file or __file__)

    def refresh_cache(self, market: str = 'AG', force: bool = False):
        # 刷新最新快照和 K 线行情缓存。
        return self._call('refresh_cache', market, force)

    def refresh_kline(self, stock_list: Optional[Sequence[str]] = None, period: str = ''):
        # 刷新指定证券和周期的历史 K 线缓存。
        return self._call('refresh_kline', list(stock_list or []), period)

